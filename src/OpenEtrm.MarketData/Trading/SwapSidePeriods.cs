using System.Collections.Immutable;
using OpenEtrm.Shared.Numerics;

namespace OpenEtrm.MarketData.Trading;

[EconomicDefinition("fixed_side_period_v1")]
public sealed record FixedSidePeriod(
    [property:IdentityField]DateOnly DeliveryFrom,[property:IdentityField]DateOnly DeliveryTo,
    [property:IdentityField]DateTimeOffset PaymentAt,[property:IdentityField]ExactRatio Allocation,
    [property:IdentityField]PaymentRule? PaymentSchedule);

[EconomicDefinition("floating_side_period_v1")]
public sealed record FloatingSidePeriod(
    [property:IdentityField]DateOnly DeliveryFrom,[property:IdentityField]DateOnly DeliveryTo,
    [property:IdentityField]DateTimeOffset FirstFixingAt,[property:IdentityField]DateTimeOffset PaymentAt,
    [property:IdentityField]FloatingAveraging Averaging,ImmutableArray<SwapProjection> Projections,
    [property:IdentityField]ImmutableArray<IndexFixing> Fixings,[property:IdentityField]SwapObservationCalendar? Calendar,
    [property:IdentityField]UnitPrice? Spread,[property:IdentityField]PaymentRule? PaymentSchedule,
    [property:IdentityField]CustomCurveProjectionBinding? CustomProjection,[property:IdentityField]ExactRatio Allocation,
    [property:IdentityField]string ObservationImplementation)
{
    [IdentityField]public CurveKey ProjectionCurve=>Projections[0].Market.Curve;
    [IdentityField]public ImmutableArray<FloatingObservation> ObservationSchedule=>[..Projections.Select(p=>new FloatingObservation(p.Contract.DeliveryFrom,p.Contract.DeliveryTo,p.AveragingQuantity))];
}

// Date and observation parameters describe all rows; they are not child sides.
public static class SwapSidePeriods
{
    public const int MaximumPeriods=1200;
    public static ImmutableArray<ExactRatio> Allocations(Side side)=>side switch {
        FixedSide fixedSide=>fixedSide.Quantities,FloatingSide floating=>floating.Quantities,
        _=>throw new MarketDataException("swap_side_periods","Select a fixed or floating payment side.")};
    internal static void Validate(ImmutableArray<(DateOnly From,DateOnly To,DateTimeOffset Payment,ExactRatio Allocation,PaymentRule? Rule)> periods,ReferenceKey currency)
    {
        if(periods.IsDefaultOrEmpty || periods.Length>MaximumPeriods)throw Invalid();
        for(var n=0;n<periods.Length;n++)
        {
            var p=periods[n];
            if(p.From>=p.To || !TradingInstant.IsSupported(p.Payment) || p.Allocation is null ||
                p.Rule is null && DateOnly.FromDateTime(p.Payment.UtcDateTime)<p.To || n>0 && periods[n-1].To!=p.From)
                throw Invalid();
            if(p.Rule is {} rule)
            {
                if(FixedSide.PaymentBoundary(rule,p.From,p.To)!=p.Payment)
                    throw new MarketDataException("payment_rule","The period must retain the exact date generated by its selected payment rule.");
                if(rule.Calendar is {} calendar && calendar.Key.Revision!=currency.Revision)
                    throw new MarketDataException("payment_calendar","The payment calendar must retain the exact currency reference revision.");
            }
        }
    }
    internal static void Monthly(Side side)
    {
        var periods=side switch {
            FixedSide f=>f.Periods.Select(p=>(p.DeliveryFrom,p.DeliveryTo,p.PaymentAt)),
            FloatingSide f=>f.Periods.Select(p=>(p.DeliveryFrom,p.DeliveryTo,p.PaymentAt)),
            _=>throw Invalid()};
        if(periods.Any(p=>p.DeliveryFrom.Year is <1901 or >2198 || p.DeliveryFrom.Day!=1 ||
            p.DeliveryFrom.AddMonths(1)!=p.DeliveryTo || p.PaymentAt.Year is <1901 or >2199))throw Invalid();
    }
    public static ImmutableArray<ExactRatio> MonthlyAllocations(ImmutableArray<QuantityPeriod> periods,MonthlyQuantityBasis basis)
    {
        if(!Enum.IsDefined(basis))throw new MarketDataException("monthly_quantity_basis","Select an explicit monthly quantity allocation convention.");
        if(periods.IsDefaultOrEmpty || periods.Length>MaximumPeriods || periods.Where((p,n)=>p is null || p.From.Day!=1 || p.From.AddMonths(1)!=p.To || n>0 && periods[n-1].To!=p.From).Any())throw Invalid();
        var days=periods.Sum(p=>p.To.DayNumber-p.From.DayNumber);
        return [..periods.Select(p=>basis switch {
            MonthlyQuantityBasis.PerMonth=>ExactRatio.One,
            MonthlyQuantityBasis.TotalEqualMonths=>new(1,periods.Length),
            MonthlyQuantityBasis.TotalCalendarDays=>new(p.To.DayNumber-p.From.DayNumber,days),
            _=>throw new MarketDataException("monthly_quantity_basis","Unsupported monthly allocation.")})];
    }
    private static MarketDataException Invalid()=>new("swap_side_periods","Supply one to 1200 ordered contiguous delivery periods with explicit quantities and payment terms.");
}
